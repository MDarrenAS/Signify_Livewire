-- 4. Catatan
-- ---------------------------------------------------------------------
-- * Tetapkan role admin hanya melalui jalur backend yang diotorisasi:
--     update public.users set role = 'admin' where email = 'email-admin@contoh.com';
--
-- * Penilaian kuis (is_correct, points_awarded, earned_points, score_percent)
--   harus dihitung dan divalidasi di sisi server, bukan dipercayakan kepada klien.
-- * Laravel terhubung sebagai backend tepercaya dan harus mengotorisasi setiap
--   operasi. Jangan mengekspos kredensial database server ke browser.
--
-- * File gambar/video isyarat disarankan disimpan di Supabase Storage;
--   kolom media_url / thumbnail_url menyimpan path atau URL-nya.
