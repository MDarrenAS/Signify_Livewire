-- Pastikan pasangan matching hanya untuk soal bertipe 'matching'
create or replace function public.check_matching_question_type()
returns trigger
language plpgsql
as $$
begin
  if not exists (
    select 1 from public.quiz_questions
    where id = new.question_id and question_type = 'matching'
  ) then
    raise exception 'quiz_matching_pairs.question_id harus merujuk soal bertipe matching';
  end if;
  return new;
end;
$$;

create trigger trg_matching_pairs_check_type
  before insert or update of question_id on public.quiz_matching_pairs
  for each row execute function public.check_matching_question_type();

