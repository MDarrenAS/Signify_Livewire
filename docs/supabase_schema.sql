-- Laravel/Fortify mengelola identitas aplikasi, bukan Supabase Auth. Tabel
-- pengguna dan data privat sengaja tidak memiliki policy Data API; Laravel
-- harus memeriksa autentikasi dan otorisasi sebelum mengaksesnya.

-- Konten yang memang publik hanya dapat dibaca dalam status published.
create policy "categories_public_read" on public.dictionary_categories
  for select to anon, authenticated using (true);

create policy "entries_public_read" on public.dictionary_entries
  for select to anon, authenticated using (status = 'published');

create policy "sign_media_public_read" on public.sign_media
  for select to anon, authenticated using (
    exists (select 1 from public.dictionary_entries e
            where e.id = dictionary_entry_id and e.status = 'published')
  );

create policy "modules_public_read" on public.learning_modules
  for select to anon, authenticated using (status = 'published');

create policy "materials_public_read" on public.learning_materials
  for select to anon, authenticated using (
    status = 'published'
    and exists (select 1 from public.learning_modules m
                where m.id = module_id and m.status = 'published')
  );

create policy "material_media_public_read" on public.material_media
  for select to anon, authenticated using (
    exists (select 1 from public.learning_materials lm
            where lm.id = material_id and lm.status = 'published')
  );

create policy "material_vocab_public_read" on public.material_vocabulary_items
  for select to anon, authenticated using (
    exists (select 1 from public.learning_materials lm
            where lm.id = material_id and lm.status = 'published')
  );

-- View backend tidak mengungkap kunci jawaban dan tetap menghormati RLS.
create view public.quiz_options_public with (security_invoker = true) as
  select o.id, o.question_id, o.option_text, o.dictionary_entry_id,
         o.sign_media_id, o.sort_order
  from public.quiz_options o
  join public.quiz_questions qq on qq.id = o.question_id
  join public.quizzes q on q.id = qq.quiz_id
  where q.status = 'published';

create view public.quiz_matching_pairs_public with (security_invoker = true) as
  select p.id, p.question_id, p.sign_media_id, p.sort_order, p.points
  from public.quiz_matching_pairs p
  join public.quiz_questions qq on qq.id = p.question_id
  join public.quizzes q on q.id = qq.quiz_id
  where q.status = 'published';

revoke all on public.quiz_options_public        from public, anon, authenticated;
revoke all on public.quiz_matching_pairs_public from public, anon, authenticated;

