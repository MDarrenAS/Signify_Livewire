create table public.dictionary_categories (
  id          integer generated by default as identity primary key,
  name        varchar(100) not null unique,
  slug        varchar(120) not null unique,
  description text,
  created_by  bigint references public.users (id) on delete set null,
  created_at  timestamptz  not null default now(),
  updated_at  timestamptz  not null default now()
);

create table public.dictionary_entries (
  id                   integer generated by default as identity primary key,
  category_id          integer references public.dictionary_categories (id) on delete set null,
  term                 varchar(200) not null,  -- kata/frasa bahasa Indonesia
  slug                 varchar(220) not null unique,
  meaning              text         not null,
  movement_description text,                   -- penjelasan gerakan isyarat
  example_usage        text,
  status               varchar(20)  not null default 'published'
                       check (status in ('draft', 'published', 'archived')),
  created_by           bigint references public.users (id) on delete set null,
  created_at           timestamptz  not null default now(),
  updated_at           timestamptz  not null default now()
);
create index idx_dictionary_entries_term        on public.dictionary_entries (term);
create index idx_dictionary_entries_category_id on public.dictionary_entries (category_id);

